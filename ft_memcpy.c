#include "libft.h"

void	*ft_memcpy(void *dest, const void *src, size_t n)
{
	unsigned char	*d;
	unsigned char	*s;

	if (!dest && !src)
		return (NULL);
	d = dest;
	s = (void *)src;
	while (n --)
	{
		*d = *s;
		d ++;
		s ++;
	}
	return (dest);
}
